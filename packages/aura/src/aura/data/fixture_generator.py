def _csv(columns: Sequence[tuple[str, str]], rows: Sequence[Sequence[str]]) -> bytes:
    """Plain RFC 4180 subset: no quoting is ever needed, and only nullable columns are empty."""
    names = [name for name, _ in columns]
    lines = [",".join(names)]
    for row in rows:
        if len(row) != len(columns):
            raise ValueError("Row width does not match the header")
        for name, cell in zip(names, row, strict=True):
            plain = cell == cell.strip() and not any(ch in cell for ch in ',"\r\n')
            if not plain or (not cell and name not in NULLABLE_COLUMNS):
                raise ValueError(f"Cell {cell!r} in {name} is not a plain CSV value")
        lines.append(",".join(row))
    return ("\n".join(lines) + "\n").encode("ascii")



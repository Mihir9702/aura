def _instant(moment: datetime) -> str:
    if moment.utcoffset() != timedelta(0):
        raise ValueError("Fixture instants must be UTC")
    return f"{moment:%Y-%m-%dT%H:%M:%S}Z"


def _price(value: Decimal) -> str:
    if value <= 0 or value != value.quantize(TICK):
        raise ValueError(f"Price {value} is not a positive multiple of the tick")
    return str(value.quantize(TICK))


def _tick(value: Decimal, rounding: str = ROUND_HALF_EVEN) -> Decimal:
    return value.quantize(TICK, rounding=rounding)


def _close_available(session: date) -> datetime:
    return new_york_to_utc(session, SESSION_CLOSE) + PUBLICATION_DELAY


def _make_bar(
    number: int,
    session: date,
    prices: tuple[Decimal, Decimal, Decimal, Decimal],
    volume: int,
) -> Bar:
    open_, high, low, close = prices
    if not (0 < low <= min(open_, close) and max(open_, close) <= high) or volume < 1:
        raise ValueError(f"Generated an invalid bar for {instrument_id(number)} on {session}")
    return Bar(
        provider_record_id=f"bar-{number:04d}-{session:%Y%m%d}",
        revision=1,
        instrument_id=instrument_id(number),
        session=session,
        interval_start=new_york_to_utc(session, SESSION_OPEN),
        interval_end=new_york_to_utc(session, SESSION_CLOSE),
        open=open_,
        high=high,
        low=low,
        close=close,
        volume=volume,
        final=True,
        available_at=_close_available(session),
    )


def _segment_by_session() -> tuple[Segment, ...]:
    expanded = tuple(segment for segment in SEGMENTS for _ in range(segment.sessions))
    if len(expanded) != SESSION_COUNT:
        raise ValueError("Process segments must cover every session exactly once")
    return expanded


def _factor_returns() -> tuple[list[Decimal], list[list[Decimal]]]:
    market_rng = _stream(_MARKET_STREAM)
    sector_rngs = [_stream(_SECTOR_STREAM, index) for index in range(len(SECTORS))]
    level = Decimal(100)
    market: list[Decimal] = []
    sectors: list[list[Decimal]] = [[] for _ in SECTORS]
    for segment in SEGMENTS:
        anchor = level
        for _ in range(segment.sessions):
            move = segment.drift + segment.volatility * market_rng.normal()
            if segment.reversion:
                move -= segment.reversion * (level / anchor - 1)
            move = move.quantize(_RATE_QUANTUM)
            market.append(move)
            level = (level * (1 + move)).quantize(_PRICE_QUANTUM)
            for index, rng in enumerate(sector_rngs):
                centre = Decimal(2 * index - (len(SECTORS) - 1)) / 2
                shock = segment.sector_spread * centre + segment.sector_volatility * rng.normal()
                sectors[index].append(shock.quantize(_RATE_QUANTUM))
    return market, sectors


def _active_sessions(spec: InstrumentSpec) -> range:
    first = LISTING_SESSION if spec.listed_on is None else 0
    last = {DELISTED: DELISTING_LAST_SESSION, STALE: STALE_LAST_SESSION}.get(
        spec.number, SESSION_COUNT - 1
    )
    return range(first, last + 1)


def _simulate(
    spec: InstrumentSpec,
    active: range,
    sessions: Sequence[date],
    segments: Sequence[Segment],
    market: Sequence[Decimal],
    sectors: Sequence[Sequence[Decimal]],
) -> list[Bar]:
    returns = _stream(_RETURN_STREAM, spec.number)
    gaps = _stream(_GAP_STREAM, spec.number)
    ranges = _stream(_RANGE_STREAM, spec.number)
    volumes = _stream(_VOLUME_STREAM, spec.number)
    previous = spec.initial_price
    bars: list[Bar] = []
    for index in active:
        segment = segments[index]
        idiosyncratic = spec.idiosyncratic_volatility * segment.idiosyncratic_scale
        move = spec.beta * market[index] + idiosyncratic * returns.normal()
        if spec.factor_sector is not None:
            move += sectors[spec.factor_sector][index]
        if spec.number == DELISTED and index >= DELISTING_DECLINE[0]:
            move += DELISTING_DECLINE[1]
        move = min(max(move, -_MAX_ABS_RETURN), _MAX_ABS_RETURN)
        spread = segment.volatility * abs(spec.beta) + idiosyncratic
        opening = previous * (1 + _GAP_SCALE * spread * gaps.normal())
        closing = previous * (1 + move)
        upper = max(opening, closing) * (1 + _RANGE_SCALE * spread * abs(ranges.normal()))
        lower = min(opening, closing) * (1 - _RANGE_SCALE * spread * abs(ranges.normal()))
        divisor = Decimal(2) if spec.number == SPLIT and index >= SPLIT_SESSION else Decimal(1)
        open_ = _tick(opening / divisor)
        close = _tick(closing / divisor)
        high = max(open_, close, _tick(upper / divisor, ROUND_CEILING))
        low = min(open_, close, _tick(lower / divisor, ROUND_FLOOR))
        noise = max(_VOLUME_FLOOR, 1 + _VOLUME_NOISE * volumes.normal())
        shares = (
            spec.base_volume * segment.volume_factor * noise * (1 + _VOLUME_MOVE * abs(move))
        ) * divisor
        volume = int(shares.quantize(Decimal(1), rounding=ROUND_HALF_EVEN))
        bars.append(_make_bar(spec.number, sessions[index], (open_, high, low, close), volume))
        previous = closing.quantize(_PRICE_QUANTUM)
    return bars


def _shifted(bar: Bar, ticks: int) -> Decimal:
    """A close different from bar.close that stays inside [low, high]."""
    for candidate in (bar.close - ticks * TICK, bar.close + ticks * TICK):
        if bar.low <= candidate <= bar.high and candidate != bar.close:
            return candidate
    raise ValueError(f"No room to shift the close of {bar.provider_record_id}")



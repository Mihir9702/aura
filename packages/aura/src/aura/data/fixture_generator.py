def _mix64(value: int) -> int:
    z = value & _MASK64
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _MASK64
    return z ^ (z >> 31)


class SplitMix64:
    """SplitMix64 on Python integers, so every platform draws the same sequence."""

    def __init__(self, seed: int) -> None:
        self._state = seed & _MASK64

    def next_u64(self) -> int:
        self._state = (self._state + _GOLDEN_GAMMA) & _MASK64
        return _mix64(self._state)

    def normal(self) -> Decimal:
        """Irwin-Hall approximation: twelve 53-bit uniforms minus 6. Mean 0, variance 1."""
        total = 0
        for _ in range(12):
            total += self.next_u64() >> 11
        return Decimal(total - 6 * (1 << 53)) / _TWO_53


def _stream(*labels: int) -> SplitMix64:
    state = SEED
    for label in labels:
        state = _mix64((state + _GOLDEN_GAMMA + label) & _MASK64)
    return SplitMix64(state)



def _nth_sunday(year: int, month: int, n: int) -> date:
    first = date(year, month, 1)
    return first + timedelta(days=(6 - first.weekday()) % 7 + 7 * (n - 1))


def dst_period(year: int) -> tuple[date, date]:
    """US daylight-saving dates in force since 2007: second Sunday of March, first of November."""
    if year < 2007:
        raise ValueError("The fixture only models the US daylight-saving rule in force since 2007")
    return _nth_sunday(year, 3, 2), _nth_sunday(year, 11, 1)


def new_york_utc_offset(day: date) -> timedelta:
    """UTC offset of America/New_York on a day without a transition (never a Sunday)."""
    if day.weekday() == 6:
        raise ValueError("Transitions happen on Sundays; the fixture never stamps a Sunday")
    start, end = dst_period(day.year)
    return timedelta(hours=-4) if start <= day < end else timedelta(hours=-5)


def new_york_to_utc(day: date, clock: time) -> datetime:
    local = datetime.combine(day, clock, tzinfo=UTC)
    return local - new_york_utc_offset(day)


def fixture_sessions() -> tuple[date, ...]:
    holidays = frozenset(FIXTURE_HOLIDAYS)
    sessions: list[date] = []
    day = FIRST_SESSION
    while len(sessions) < SESSION_COUNT:
        if day.weekday() < 5 and day not in holidays:
            sessions.append(day)
        day += timedelta(days=1)
    for holiday in FIXTURE_HOLIDAYS:
        if holiday.weekday() >= 5 or not FIRST_SESSION < holiday < sessions[-1]:
            raise ValueError(f"Fixture holiday {holiday} must be a weekday inside the window")
    return tuple(sessions)



def build_dataset() -> dict[str, bytes]:
    """Return every dataset file keyed by name. Pure: no clock, filesystem or environment."""
    with localcontext(_decimal_context()):
        sessions = fixture_sessions()
        segments = _segment_by_session()
        market, sectors = _factor_returns()
        clean = {
            spec.number: _simulate(
                spec, _active_sessions(spec), sessions, segments, market, sectors
            )
            for spec in INSTRUMENTS
        }
        unknown_day = range(UNKNOWN_INSTRUMENT[1], UNKNOWN_INSTRUMENT[1] + 1)
        (unknown,) = _simulate(UNKNOWN_SPEC, unknown_day, sessions, segments, market, sectors)
        build = _deliveries(clean, unknown, sessions)
        files: dict[str, bytes] = {
            INSTRUMENTS_FILE: _csv(INSTRUMENT_COLUMNS, _instrument_rows(sessions)),
            SYMBOLS_FILE: _csv(SYMBOL_COLUMNS, _symbol_rows(sessions)),
            UNIVERSE_FILE: _csv(UNIVERSE_COLUMNS, _universe_rows(sessions)),
            BARS_FILE: _csv(BAR_COLUMNS, [d.bar.cells() for d in build.deliveries]),
            ACTIONS_FILE: _csv(ACTION_COLUMNS, _action_rows(sessions)),
        }
        scenarios = _scenarios(build)
        files[README_FILE] = _readme(build, files, scenarios)
        files[MANIFEST_FILE] = _manifest(build, files, scenarios)
    return files


def write_dataset(out: Path) -> dict[str, bytes]:
    files = build_dataset()
    out.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (out / name).write_bytes(content)
    return files


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog=f"python -m {GENERATOR_MODULE}",
        description=f"Write the {DATASET_ID} synthetic fixture (NOT market data).",
    )
    parser.add_argument("--out", required=True, type=Path, help="Directory to write into")
    args = parser.parse_args(argv)
    out: Path = args.out
    for name, content in write_dataset(out).items():
        digest = hashlib.sha256(content).hexdigest()
        print(f"{name}: {len(content)} bytes sha256={digest}")
    print(f"Wrote {DATASET_ID} ({PROVENANCE_CLASS}, not market data) to {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

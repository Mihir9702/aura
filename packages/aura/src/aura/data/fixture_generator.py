def _dst_transitions(sessions: Sequence[date]) -> list[JSON]:
    transitions: list[JSON] = []
    for year in range(sessions[0].year, sessions[-1].year + 1):
        for change, offset in zip(dst_period(year), ("-04:00", "-05:00"), strict=True):
            if sessions[0] < change < sessions[-1]:
                after = next(s for s in sessions if s > change)
                transitions.append(
                    {
                        "date": change.isoformat(),
                        "utc_offset_after": offset,
                        "first_session_after": after.isoformat(),
                        "interval_start_utc_after": _instant(new_york_to_utc(after, SESSION_OPEN)),
                    }
                )
    return transitions


